#!/usr/bin/env python3
"""Create or update translation tables so they have every key of the source.

    scripts/i18n/skeleton.py            all languages
    scripts/i18n/skeleton.py fr ru      only these

Existing translations are kept (in source order); missing keys are added
with the English text as a placeholder and a `// TODO` comment, keys the
source no longer has are dropped. Run it after adding strings to a source
table, then translate the TODO lines and run scripts/i18n/check.py.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import catalog as c  # noqa: E402

NAMES = {"zh": "Simplified Chinese (zh-Hans)", "es": "Spanish (es)", "fr": "French (fr)", "it": "Italian (it)", "ru": "Russian (ru)"}


def write(name, src_path, lang, path):
    source = c.read_source(src_path)
    old = dict(c.read_translation(path))
    text = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    old_todo = set(re.findall(r'\("([^"]+)",.*// TODO', text))
    need = c.needed_keys(source, lang)
    rel = os.path.relpath(src_path, os.path.dirname(path))
    lines = [
        f"//! {NAMES[lang]} strings for `{rel}` (see `manta_plugin::i18n`).",
        "//! Generated by scripts/i18n/skeleton.py, translated by hand.",
        "",
        "use manta_plugin::i18n::Translations;",
        "",
        "pub const ENTRIES: Translations = &[",
    ]
    todo = 0
    for key in need:
        if key in old and key not in old_todo:
            lines.append(f'    ("{c.escape(key)}", "{c.escape(old[key])}"),')
        else:
            todo += 1
            lines.append(f'    ("{c.escape(key)}", "{c.escape(need[key][0])}"), // TODO')
    lines.append("];")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return todo


def write_app_mod(lang, areas):
    """crates/app/src/i18n/catalog/<lang>/mod.rs: one module per area."""
    path = os.path.join(c.ROOT, "crates/app/src/i18n/catalog", lang, "mod.rs")
    lines = [
        f"//! {NAMES[lang]} translations of the app catalog, one file per area",
        "//! (same keys as the source tables one level up). Generated by",
        "//! scripts/i18n/skeleton.py.",
        "",
        "use manta_plugin::i18n::Translations;",
        "",
    ]
    lines += [f"mod {a};" for a in areas]
    lines += ["", "pub const ALL: &[Translations] = &["]
    lines += [f"    {a}::ENTRIES," for a in areas]
    lines += ["];"]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def main():
    langs = sys.argv[1:] or c.LANGS
    areas = []
    for name, src, paths in c.catalogs():
        if name.startswith("app/"):
            areas.append(name[4:])
        for l in langs:
            todo = write(name, src, l, paths[l])
            if todo:
                print(f"{name} [{l}]: {todo} to translate")
    for l in langs:
        write_app_mod(l, areas)


if __name__ == "__main__":
    main()
