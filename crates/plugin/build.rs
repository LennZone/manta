//! Embeds the plugins that ship with Manta (the top-level `plugins/`
//! folder plus the `hello-python` example) into the binary, so Settings →
//! Plugins → Available can install them wherever the app lives. Generates
//! `$OUT_DIR/bundled.rs` (see `src/bundled.rs`).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Not shipped: caches, VCS data and the plugins' own test suites.
fn skip(name: &str) -> bool {
    matches!(
        name,
        ".git" | "__pycache__" | ".DS_Store" | "tests" | ".pytest_cache"
    ) || name.ends_with(".pyc")
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf, bool)>) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<_> = rd.flatten().collect();
    entries.sort_by_key(|e| e.file_name());
    for e in entries {
        let name = e.file_name().to_string_lossy().into_owned();
        if skip(&name) {
            continue;
        }
        let path = e.path();
        let Ok(ft) = e.file_type() else { continue };
        if ft.is_dir() {
            collect(root, &path, out);
        } else if ft.is_file() {
            #[cfg(unix)]
            let exec = {
                use std::os::unix::fs::PermissionsExt;
                e.metadata()
                    .map(|m| m.permissions().mode() & 0o111 != 0)
                    .unwrap_or(false)
            };
            #[cfg(not(unix))]
            let exec = false;
            let rel = path
                .strip_prefix(root)
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            out.push((rel, path, exec));
        }
    }
}

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let repo = manifest_dir.join("../..");
    let mut folders: Vec<PathBuf> = Vec::new();
    let plugins = repo.join("plugins");
    println!("cargo:rerun-if-changed={}", plugins.display());
    if let Ok(rd) = std::fs::read_dir(&plugins) {
        let mut v: Vec<PathBuf> = rd
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.join("plugin.toml").is_file())
            .collect();
        v.sort();
        folders.extend(v);
    }
    let hello = repo.join("examples/plugins/hello-python");
    println!("cargo:rerun-if-changed={}", hello.display());
    if hello.join("plugin.toml").is_file() {
        folders.push(hello);
    }

    let mut code = String::from("// Generated by build.rs: the bundled plugins.\npub(crate) static BUNDLED: &[RawPlugin] = &[\n");
    for f in &folders {
        let folder = f.file_name().unwrap().to_string_lossy().into_owned();
        let mut files = Vec::new();
        collect(f, f, &mut files);
        writeln!(code, "    RawPlugin {{ folder: {folder:?}, files: &[").unwrap();
        for (rel, path, exec) in files {
            let abs = std::fs::canonicalize(&path).unwrap_or(path);
            writeln!(code, "        RawFile {{ path: {rel:?}, bytes: include_bytes!({:?}), executable: {exec} }},", abs.display().to_string())
                .unwrap();
        }
        code.push_str("    ] },\n");
    }
    code.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("bundled.rs");
    std::fs::write(out, code).unwrap();
}
