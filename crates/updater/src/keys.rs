//! Ed25519 keys and signatures.
//!
//! Key files are text: optional `#` comment lines, then one base64 line.
//! * public key: the 32-byte Ed25519 public key (`packaging/update-public-key.txt`)
//! * private key: the 32-byte Ed25519 seed (`~/.config/manta/update-signing-key`, mode 0600)

use base64::engine::general_purpose::STANDARD as B64;
use base64::Engine;
use ed25519_dalek::{Signature, Signer, SigningKey, VerifyingKey};

use crate::error::{Result, UpdateError};
use crate::manifest::{manifest_message, release_message, Release};

pub use ed25519_dalek::{SigningKey as PrivateKey, VerifyingKey as PublicKey};

/// The public key compiled into this build (see `build.rs`), if any.
pub fn embedded_public_key() -> Result<VerifyingKey> {
    let b64 = env!("MANTA_UPDATE_PUBKEY_EMBEDDED");
    if b64.is_empty() {
        return Err(UpdateError::Disabled(
            "this build has no update signing key (run manta-update-keygen and rebuild)".into(),
        ));
    }
    parse_public_key(b64)
        .map_err(|e| UpdateError::Disabled(format!("the built-in update key is invalid ({e})")))
}

/// First non-comment, non-empty line of a key file.
fn key_line(text: &str) -> &str {
    text.lines()
        .map(str::trim)
        .find(|l| !l.is_empty() && !l.starts_with('#'))
        .unwrap_or("")
}

fn decode32(text: &str, what: &str) -> Result<[u8; 32]> {
    let bytes = B64
        .decode(key_line(text))
        .map_err(|e| UpdateError::Signature(format!("{what} is not valid base64 ({e})")))?;
    bytes
        .try_into()
        .map_err(|_| UpdateError::Signature(format!("{what} must be 32 bytes")))
}

/// Parses a public key file or a bare base64 key.
pub fn parse_public_key(text: &str) -> Result<VerifyingKey> {
    let bytes = decode32(text, "public key")?;
    VerifyingKey::from_bytes(&bytes)
        .map_err(|e| UpdateError::Signature(format!("invalid public key ({e})")))
}

/// Parses a private key file (the 32-byte seed).
pub fn parse_private_key(text: &str) -> Result<SigningKey> {
    Ok(SigningKey::from_bytes(&decode32(text, "private key")?))
}

/// A fresh key pair from the OS random number generator.
pub fn generate_private_key() -> Result<SigningKey> {
    let mut seed = [0u8; 32];
    getrandom::fill(&mut seed)
        .map_err(|e| UpdateError::Io(format!("no secure random numbers: {e}")))?;
    let key = SigningKey::from_bytes(&seed);
    seed.fill(0);
    Ok(key)
}

pub fn public_key_b64(key: &VerifyingKey) -> String {
    B64.encode(key.as_bytes())
}

pub fn private_key_file_contents(key: &SigningKey) -> String {
    format!(
        "# Manta update signing key (Ed25519 seed, base64).\n# SECRET: never commit, share or upload this file. Back it up offline.\n{}\n",
        B64.encode(key.to_bytes())
    )
}

pub fn public_key_file_contents(key: &VerifyingKey) -> String {
    format!(
        "# Manta update public key (Ed25519, base64). Generated by manta-update-keygen.\n# Compiled into the app; it verifies update.json and every update ZIP.\n{}\n",
        public_key_b64(key)
    )
}

pub(crate) fn decode_signature(b64: &str) -> std::result::Result<Signature, String> {
    let bytes = B64
        .decode(key_line(b64))
        .map_err(|e| format!("signature is not valid base64 ({e})"))?;
    let arr: [u8; 64] = bytes
        .try_into()
        .map_err(|_| "signature must be 64 bytes".to_string())?;
    Ok(Signature::from_bytes(&arr))
}

/// Rejects field values that could make [`release_message`] ambiguous.
fn check_release_fields(release: &Release) -> Result<()> {
    let ok_hex =
        release.sha256.len() == 64 && release.sha256.bytes().all(|b| b.is_ascii_hexdigit());
    if !ok_hex || crate::check::OsVersion::parse(&release.min_macos).is_none() {
        return Err(UpdateError::Signature(format!(
            "release {} has malformed fields",
            release.version
        )));
    }
    Ok(())
}

/// Fills `release.signature`.
pub fn sign_release(key: &SigningKey, app_id: &str, release: &mut Release) -> Result<()> {
    check_release_fields(release)?;
    release.sha256 = release.sha256.to_ascii_lowercase();
    release.signature = B64.encode(key.sign(&release_message(app_id, release)).to_bytes());
    Ok(())
}

/// Verifies `release.signature` for `app_id`.
pub fn verify_release(key: &VerifyingKey, app_id: &str, release: &Release) -> Result<()> {
    check_release_fields(release)?;
    let sig = decode_signature(&release.signature).map_err(UpdateError::Signature)?;
    key.verify_strict(&release_message(app_id, release), &sig)
        .map_err(|_| {
            UpdateError::Signature(format!(
                "release {} is not signed by the Manta update key",
                release.version
            ))
        })
}

/// Signature for `update.json.sig` (base64 + newline).
pub fn sign_manifest(key: &SigningKey, manifest_bytes: &[u8]) -> String {
    format!(
        "{}\n",
        B64.encode(key.sign(&manifest_message(manifest_bytes)).to_bytes())
    )
}

/// Verifies `update.json` against the contents of `update.json.sig`.
pub fn verify_manifest(key: &VerifyingKey, manifest_bytes: &[u8], sig_text: &str) -> Result<()> {
    let sig = decode_signature(sig_text)
        .map_err(|e| UpdateError::Signature(format!("update.json.sig: {e}")))?;
    key.verify_strict(&manifest_message(manifest_bytes), &sig)
        .map_err(|_| {
            UpdateError::Signature("update.json is not signed by the Manta update key".into())
        })
}
