use eframe::egui;

fn main() -> eframe::Result {
    logging::init();
    // `MANTA_QL_SELFTEST=/path/file.png` shows the real Quick Look panel
    // for 2 s, logs what AppKit reports and quits.
    #[cfg(target_os = "macos")]
    if let Ok(spec) = std::env::var("MANTA_QL_SELFTEST") {
        return quicklook::native::SelfTest::run(&spec);
    }
    // `MANTA_DRAG_SELFTEST=1|manual`: native drag-out session check, see
    // `native_drag::selftest`.
    #[cfg(target_os = "macos")]
    if let Ok(spec) = std::env::var("MANTA_DRAG_SELFTEST") {
        std::process::exit(native_drag::selftest::SelfTest::run(&spec));
    }
    // `MANTA_DV_SELFTEST=status|on|off`: see `default_viewer::selftest`.
    if let Some(code) = default_viewer::selftest::run_before_ui() {
        std::process::exit(code);
    }
    // Catch "open folder" / "Show in Finder" Apple Events (also the one
    // that launched us) once AppKit is about to finish launching.
    #[cfg(target_os = "macos")]
    default_viewer::native::register();
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title("Manta")
            .with_inner_size([1280.0, 800.0])
            .with_min_inner_size([800.0, 480.0])
            // Dock icon when run unbundled (`cargo run`); Manta.app uses AppIcon.icns.
            // Generated by packaging/icon/make_icons.py.
            .with_icon(
                eframe::icon_data::from_png_bytes(include_bytes!("../assets/app-icon.png"))
                    .unwrap_or_default(),
            ),
        ..Default::default()
    };
    eframe::run_native(
        "Manta",
        options,
        Box::new(|cc| Ok(Box::new(app::MantaApp::new(cc)))),
    )
}
